export type I18nKey = keyof (typeof DICT)['zh'];

export function detectDefaultLocale(hostLocale?: string): Locale {
  const candidate = (hostLocale || (typeof navigator !== 'undefined' ? navigator.language : '') || '').toLowerCase();
  if (candidate.startsWith('zh')) return 'zh';
  if (candidate.startsWith('en')) return 'en';
  return 'zh';
}

export function t(
  locale: Locale,
  key: I18nKey,
  vars?: Record<string, string | number>,
): string {
  const table = DICT[locale] || DICT.zh;
  let text: string = table[key] ?? DICT.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.split(`{${k}}`).join(String(v));
    }
  }
  return text;
}
